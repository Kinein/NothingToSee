#!/usr/bin/env node
// Writes MAP.md and SYMBOLS.tsv from js/ORDER.txt and the modules themselves; with --headers it also
// refreshes the `//@` header at the top of every module (purpose, what it defines, what it leans on).
// No dependencies. Run after adding, moving or renaming top-level things:   node tools/map.js --headers
'use strict';
const fs = require('fs'),
  path = require('path');
const ROOT = path.resolve(__dirname, '..');
const rd = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');

// ── modules, in build order, with their one-line purpose (the comment after # in ORDER.txt)
const MODS = rd('js/ORDER.txt')
  .split('\n')
  .map((l) => l.trim().replace(/^dev\s+/, ''))
  .filter((l) => l && !l.startsWith('#'))
  .map((l) => {
    const [f, ...rest] = l.split('#');
    return { file: 'js/' + f.trim(), purpose: rest.join('#').trim() };
  });

const { KW, scan, topLevel } = require('./jsscan');

// ── run
const mods = MODS.map((m) => {
  const raw = rd(m.file);
  const body = raw
    .split('\n')
    .filter((l, i, a) => !(l.startsWith('//@') && a.slice(0, i).every((x) => x.startsWith('//@'))))
    .join('\n');
  const toks = scan(body);
  const hdr = raw.split('\n').findIndex((l) => !l.startsWith('//@'));
  const defs = topLevel(toks).map((d) => ({ ...d, line: d.line + hdr }));
  const ids = new Map();
  for (const t of toks) if (t.t === 'id' && !t.dot && !t.key && !KW.has(t.v)) ids.set(t.v, (ids.get(t.v) || 0) + 1);
  if (toks.open)
    console.warn('warning: ' + m.file + ' ends with ' + toks.open + ' bracket(s) open (tokenizer confused?)');
  return { ...m, raw, body, defs, ids, lines: body.split('\n').length - 1 };
});
const owner = new Map();
const dupes = [];
for (const m of mods)
  for (const d of m.defs) {
    if (owner.has(d.name)) dupes.push(d.name + ' in ' + owner.get(d.name).file + ' and ' + m.file);
    else owner.set(d.name, m);
  }
for (const m of mods) {
  m.deps = new Map();
  for (const [id, c] of m.ids) {
    const o = owner.get(id);
    if (o && o !== m) m.deps.set(o, (m.deps.get(o) || 0) + c);
  }
}
for (const m of mods) m.users = mods.filter((x) => x.deps.has(m));
const short = (f) => f.replace(/^js\//, '').replace(/\.js$/, '');
const orderIdx = new Map(mods.map((m, i) => [m, i]));

// MAP.md
const out = [];
out.push(
  '# Module map',
  '',
  'Generated by `node tools/map.js` from js/ORDER.txt and the code. Do not edit by hand. Dependencies are found by name, so they are approximate: a local variable that shares a name with a top-level one elsewhere shows up as a use.',
  '',
);
out.push(
  'Read this first. Find the module that owns what you need (or `grep -w name SYMBOLS.tsv`), then open only that file and the few it depends on.',
  '',
);
out.push(
  '`→` uses: the modules whose top-level names this one uses (most used first). `←` used by: how many modules use this one.',
  '',
);
out.push("`#n` is the module's place in the build order (js/ORDER.txt).", '');
const folders = [...new Set(mods.map((m) => m.file.split('/')[1]))];
const grouped = folders.flatMap((f) => mods.filter((m) => m.file.split('/')[1] === f));
let folder = '';
for (const m of grouped) {
  const f = m.file.split('/')[1];
  if (f !== folder) {
    folder = f;
    out.push('## ' + f + '/', '');
  }
  const names = m.defs.map((d) => d.name);
  const deps = [...m.deps.entries()].sort((a, b) => b[1] - a[1]).map(([o]) => short(o.file));
  out.push('### ' + short(m.file) + '  ·  #' + (orderIdx.get(m) + 1) + '  ·  ' + m.lines + ' lines', '', m.purpose, '');
  out.push(
    '- **Defines (' +
      names.length +
      '):** ' +
      (names.length
        ? names
            .slice(0, 60)
            .map((x) => '`' + x + '`')
            .join(' ') + (names.length > 60 ? ' … +' + (names.length - 60) : '')
        : '—'),
  );
  out.push(
    '- **→ uses:** ' +
      (deps.length ? deps.slice(0, 14).join(', ') + (deps.length > 14 ? ' … +' + (deps.length - 14) : '') : '—'),
  );
  out.push(
    '- **← used by:** ' +
      m.users.length +
      (m.users.length && m.users.length <= 6 ? ' (' + m.users.map((u) => short(u.file)).join(', ') + ')' : ''),
    '',
  );
}
if (dupes.length) out.push('## Names defined twice (check these)', '', ...dupes.map((d) => '- ' + d), '');
fs.writeFileSync(path.join(ROOT, 'MAP.md'), out.join('\n'));

// SYMBOLS.tsv
const sym = ['name\tmodule\tline\tkind'];
for (const m of mods) for (const d of m.defs) sym.push([d.name, m.file, d.line, d.kind].join('\t'));
fs.writeFileSync(path.join(ROOT, 'SYMBOLS.tsv'), sym.join('\n') + '\n');

// headers
if (process.argv.includes('--headers')) {
  for (const m of mods) {
    const names = m.defs
      .filter((d) => d.kind === 'function' || /^[A-Z][A-Z0-9_]+$/.test(d.name) || d.kind === 'class')
      .map((d) => d.name);
    const deps = [...m.deps.entries()].sort((a, b) => b[1] - a[1]).map(([o]) => short(o.file));
    const wrap = (label, list, max) => {
      const s = list.slice(0, max).join(', ') + (list.length > max ? ', …' : '');
      return '//@ ' + label + (s || '—');
    };
    const h = [
      '//@ ' + short(m.file) + ' — ' + m.purpose,
      wrap('Defines: ', names, 16),
      wrap('Uses:    ', deps, 10),
      '//@ (header made by tools/map.js; stripped by build.py)',
    ];
    fs.writeFileSync(path.join(ROOT, m.file), h.join('\n') + '\n' + m.body);
  }
}
const nDefs = mods.reduce((s, m) => s + m.defs.length, 0);
console.log(
  'MAP.md + SYMBOLS.tsv: ' +
    mods.length +
    ' modules, ' +
    nDefs +
    ' top-level names' +
    (dupes.length ? ', ' + dupes.length + ' defined twice' : '') +
    (process.argv.includes('--headers') ? ', headers refreshed' : ''),
);
