#!/usr/bin/env node
// Writes docs/STATE.md: every field of the game state G (from freshG in game/state.js) and of a character,
// with its starting value and which modules write and read it. Found by name, so treat it as a map, not proof.
//   node tools/state.js
'use strict';
const fs = require('fs'), path = require('path');
const { scan } = require('./jsscan');
const ROOT = path.resolve(__dirname, '..');
const rd = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');
const files = rd('js/ORDER.txt').split('\n').map((l) => l.split('#')[0].trim()).filter((l) => l && !l.startsWith('dev ')).map((f) => 'js/' + f);
const src = Object.fromEntries(files.map((f) => [f, rd(f).split('\n').filter((l) => !l.startsWith('//@')).join('\n')]));
const short = (f) => f.replace(/^js\//, '').replace(/\.js$/, '');

// the fields of freshG's object literal, at its top level, with their starting values
function literalFields(text, open) {
  const toks = scan(text.slice(open));
  const out = [];
  const base = toks[0].d;   // the `{`
  for (let k = 1; k < toks.length; k++) {
    const t = toks[k];
    if (t.v === '}' && t.d === base) break;
    if (t.d === base + 1 && t.t === 'id' && toks[k + 1] && toks[k + 1].v === ':' && (toks[k - 1].v === '{' || toks[k - 1].v === ',')) out.push(t.v);
  }
  return out;
}
function startValues(text, open, fields) {   // the source text of each field's starting value, roughly
  const body = text.slice(open);
  const vals = {};
  for (const f of fields) {
    const m = new RegExp('[{,\\s]' + f + ':\\s*').exec(body);
    if (!m) continue;
    let i = m.index + m[0].length, depth = 0, j = i;
    for (; j < body.length; j++) { const c = body[j]; if ('[{('.includes(c)) depth++; else if (')}]'.includes(c)) { if (depth === 0) break; depth--; } else if (c === ',' && depth === 0) break; }
    const v = body.slice(i, j).trim();
    vals[f] = v.length > 48 ? v.slice(0, 45) + '…' : v;
  }
  return vals;
}
function usage(obj, field) {
  const w = new Set(), r = new Set();
  const re = new RegExp('\\b' + obj + '\\.' + field + '\\b(\\s*(?:\\+\\+|--|[-+*/|&]?=(?!=)))?', 'g');
  for (const f of files) {
    let m; while ((m = re.exec(src[f]))) (m[1] ? w : r).add(short(f));
  }
  return { w: [...w], r: [...r].filter((x) => !w.has(x)) };
}
const st = rd('js/game/state.js');
const gOpen = st.indexOf('return {', st.indexOf('function freshG')) + 7;
const gFields = literalFields(st, gOpen);
const gVals = startValues(st, gOpen, gFields);
const out = ['# Game state', '', 'Generated by `node tools/state.js`. Do not edit by hand.', '',
  'All live state sits in a handful of shared globals (every module can reach them):', '',
  '| Name | What it is | Made in |', '| --- | --- | --- |',
  '| `G` | The current game: time, THEIR plan, your inventory, evidence, flags. Saved to localStorage. | game/state (`freshG`, `newGame`, `loadGame`) |',
  '| `PLAYER` | You, a character record (below) with `isPlayer` and `needs` | sim/characters, game/state (`setupPlayer`) |',
  '| `NPC` / `CHARS` | The townsfolk by id / everyone including you, as character records | sim/core, town/cast (`setupCast`) |',
  '| `UI` | What the interface is showing: menus, notes, focus, the board | ui/interface |',
  '| `R` / `cam` / `gl` | The renderer, the camera, the WebGL context | gfx/renderer, gfx/gl |',
  '| `HX`, `CAP`, `HUNT`, `ARREST` | Running set pieces: the horror layer, being taken, a hunt, an arrest | horror/layer, taken/coming, chase/hunt, town/arrest |', '',
  '## `G` fields', '', '"Written in" lists modules that assign it (besides `freshG`); "Read in" those that only read it.', '',
  '| Field | Starts as | Written in | Read in |', '| --- | --- | --- | --- |'];
for (const f of gFields) {
  const u = usage('G', f);
  out.push('| `' + f + '` | `' + (gVals[f] || '').replace(/\|/g, '\\|') + '` | ' + (u.w.join(', ') || '—') + ' | ' + (u.r.slice(0, 8).join(', ') + (u.r.length > 8 ? ', …' : '') || '—') + ' |');
}
// fields added to G later, outside freshG
const extra = new Set();
for (const f of files) { const re = /\bG\.([A-Za-z_]\w*)\s*(?:=(?!=)|\+\+|--|[-+*/|]=)/g; let m; while ((m = re.exec(src[f]))) if (!gFields.includes(m[1])) extra.add(m[1]); }
if (extra.size) {
  out.push('', '## `G` fields added on the fly', '', 'Not in `freshG`, so they start undefined. Candidates to add there with a starting value.', '', '| Field | Written in |', '| --- | --- |');
  for (const f of [...extra].sort()) out.push('| `' + f + '` | ' + usage('G', f).w.join(', ') + ' |');
}
// character records
const chSrc = rd('js/sim/characters.js');
const cAt = chSrc.indexOf('const c = {', chSrc.indexOf('function makeChar'));
const cOpen = cAt >= 0 ? cAt + 'const c = '.length : -1;
if (cOpen > 0) {
  const cFields = literalFields(chSrc, cOpen);
  out.push('', '## Character fields (`makeChar` in sim/characters)', '', 'People are plain objects; code reaches them as `n`, `c`, `PLAYER`, `NPC.<id>`, so uses are not traced here.', '', cFields.map((f) => '`' + f + '`').join(' '));
}
fs.mkdirSync(path.join(ROOT, 'docs'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'docs/STATE.md'), out.join('\n') + '\n');
console.log('docs/STATE.md: ' + gFields.length + ' G fields, ' + extra.size + ' added on the fly');
